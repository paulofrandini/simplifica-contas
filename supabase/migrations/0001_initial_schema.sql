begin;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  display_name text,
  plan text not null default 'free' check (plan in ('free', 'premium')),
  income_confirmation_version integer not null default 0,
  card_workflow_version integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.transactions (
  id integer generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  title text not null,
  category text not null,
  amount_cents integer not null check (amount_cents > 0),
  type text not null check (type in ('income', 'expense')),
  icon text not null default 'food',
  transaction_date timestamptz not null default now(),
  recurrence_id uuid,
  paid boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists transactions_user_date_idx on public.transactions(user_id, transaction_date);

create table if not exists public.credit_cards (
  id integer generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  name text not null,
  last_four text not null default '0000',
  brand text not null default 'BANCO',
  limit_cents integer not null default 0 check (limit_cents >= 0),
  invoice_cents integer not null default 0 check (invoice_cents >= 0),
  due_day integer not null default 10 check (due_day between 1 and 28),
  management_mode text not null default 'total' check (management_mode in ('total', 'items')),
  created_at timestamptz not null default now()
);
create index if not exists credit_cards_user_idx on public.credit_cards(user_id);

create table if not exists public.bills (
  id integer generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  title text not null,
  amount_cents integer not null check (amount_cents > 0),
  due_label text not null,
  due_day integer not null default 1 check (due_day between 1 and 28),
  billing_month text not null check (billing_month = 'legacy' or billing_month ~ '^\\d{4}-(0[1-9]|1[0-2])$'),
  recurrence_id uuid,
  category text not null default 'Outros',
  paid boolean not null default false,
  icon text not null default 'home',
  payment_method text not null default 'direct' check (payment_method in ('direct', 'card')),
  card_id integer references public.credit_cards(id) on delete set null,
  card_transfer_mode text not null default 'confirm' check (card_transfer_mode in ('automatic', 'confirm')),
  card_transferred boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists bills_user_idx on public.bills(user_id);
create index if not exists bills_user_month_idx on public.bills(user_id, billing_month);

create table if not exists public.card_invoices (
  id integer generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  card_id integer not null references public.credit_cards(id) on delete cascade,
  billing_month text not null check (billing_month ~ '^\\d{4}-(0[1-9]|1[0-2])$'),
  amount_cents integer not null default 0 check (amount_cents >= 0),
  paid boolean not null default false,
  created_at timestamptz not null default now(),
  constraint card_invoices_card_month_uidx unique (card_id, billing_month)
);
create index if not exists card_invoices_user_month_idx on public.card_invoices(user_id, billing_month);

create table if not exists public.card_purchases (
  id integer generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  card_id integer not null references public.credit_cards(id) on delete cascade,
  title text not null,
  total_cents integer not null check (total_cents > 0),
  installment_count integer not null default 1 check (installment_count between 1 and 60),
  first_payment_month text not null check (first_payment_month ~ '^\\d{4}-(0[1-9]|1[0-2])$'),
  created_at timestamptz not null default now()
);
create index if not exists card_purchases_user_card_idx on public.card_purchases(user_id, card_id);

create table if not exists public.loan_installments (
  id integer generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  title text not null,
  kind text not null default 'loan' check (kind in ('loan', 'bank_limit')),
  amount_cents integer not null check (amount_cents > 0),
  billing_month text not null check (billing_month ~ '^\\d{4}-(0[1-9]|1[0-2])$'),
  installment_number integer not null check (installment_number > 0),
  installment_count integer not null check (installment_count between 1 and 60),
  recurrence_id uuid not null,
  paid boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists loan_installments_user_month_idx on public.loan_installments(user_id, billing_month);

create table if not exists public.investments (
  id integer generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  institution text not null,
  amount_cents integer not null check (amount_cents > 0),
  created_at timestamptz not null default now()
);
create index if not exists investments_user_idx on public.investments(user_id);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, email, display_name)
  values (
    new.id,
    coalesce(new.email, ''),
    nullif(new.raw_user_meta_data ->> 'full_name', '')
  )
  on conflict (id) do update set
    email = excluded.email,
    display_name = coalesce(excluded.display_name, public.profiles.display_name);
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert or update of email, raw_user_meta_data on auth.users
  for each row execute procedure public.handle_new_user();

do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'profiles', 'transactions', 'bills', 'credit_cards',
    'card_invoices', 'card_purchases', 'loan_installments', 'investments'
  ] loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('revoke all on table public.%I from anon', table_name);
    execute format('grant select, insert, update, delete on table public.%I to authenticated', table_name);
  end loop;
end $$;

grant usage, select on all sequences in schema public to authenticated;

drop policy if exists profiles_owner_all on public.profiles;
create policy profiles_owner_all on public.profiles
  for all to authenticated
  using ((select auth.uid()) = id)
  with check ((select auth.uid()) = id);

do $$
declare
  table_name text;
  policy_name text;
begin
  foreach table_name in array array[
    'transactions', 'bills', 'credit_cards', 'card_invoices',
    'card_purchases', 'loan_installments', 'investments'
  ] loop
    policy_name := table_name || '_owner_all';
    execute format('drop policy if exists %I on public.%I', policy_name, table_name);
    execute format(
      'create policy %I on public.%I for all to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id)',
      policy_name,
      table_name
    );
  end loop;
end $$;

commit;
